"""Turns IANA's RDAP bootstrap (https://data.iana.org/rdap/dns.json) into
ios/Spectra/Links/RDAPServers.swift, so the app can ask each zone's registry
directly. Usage: python3 -I data/tools/build_rdap.py dns.json ios/Spectra/Links/RDAPServers.swift"""
import json, sys

source, target = sys.argv[1], sys.argv[2]
data = json.load(open(source, encoding="utf-8"))
lines = []
skipped = 0
for tlds, urls in data["services"]:
    # App Transport Security blocks plain http, so an https server is required.
    https = [u for u in urls if u.lower().startswith("https://")]
    if not https:
        skipped += len(tlds)
        continue
    base = https[0] if https[0].endswith("/") else https[0] + "/"
    lines.append(f"{' '.join(sorted(t.lower() for t in tlds))}:{base}")
lines.sort()
with open(target, "w", encoding="utf-8") as out:
    out.write("// Generated by Tools/build_rdap.py from https://data.iana.org/rdap/dns.json\n")
    out.write(f"// (publication {data['publication']}). Do not edit by hand.\n\n")
    out.write("nonisolated enum RDAPServers {\n")
    out.write(f'    static let publication = "{data["publication"]}"\n\n')
    out.write("    /// One zone group per line: space-separated TLDs, a colon, the RDAP base URL.\n")
    out.write('    static let table = """\n')
    for line in lines:
        out.write(f"    {line}\n")
    out.write('    """\n}\n')
print(len(lines), "server groups written,", skipped, "http-only TLDs skipped")
